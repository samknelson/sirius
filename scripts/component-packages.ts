import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export interface ComponentPackageManifest {
  id: string;
  definitions: string;
  shared?: string[];
  server?: string[];
  browser?: Record<string, string>;
  schema?: string[];
  migrations?: string[];
  startup?: string;
  storage?: string;
  metadata?: string;
  client?: string;
  contributions?: string;
  coreMigrations?: string[];
  maintenanceGuards?: Record<string, {
    handlerContainers: string[];
    handlerProperty: string;
    vendorIdentifiers: string[];
  }>;
}

/** Build-time discovery only. Runtime bundles contain literal imports, never filesystem scans. */
export function discoverComponentPackages(root = resolve(import.meta.dirname, "..")) {
  const directory = resolve(root, "components");
  if (!existsSync(directory)) return [];
  const ids = new Set<string>();
  return readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && !entry.name.startsWith("."))
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(entry => {
      const packageRoot = resolve(directory, entry.name);
      const manifestPath = resolve(packageRoot, "component-package.json");
      if (!existsSync(manifestPath)) throw new Error(`Missing package manifest: ${manifestPath}`);
      const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as ComponentPackageManifest;
      if (!manifest.id || !/^[a-z0-9][a-z0-9._-]*$/.test(manifest.id) || ids.has(manifest.id)) {
        throw new Error(`Invalid or duplicate package id in ${manifestPath}`);
      }
      ids.add(manifest.id);
      const modulePath = (path: string) => {
        if (typeof path !== "string") throw new Error(`Invalid contribution in ${manifestPath}`);
        const absolute = resolve(packageRoot, path);
        if (!absolute.startsWith(packageRoot + sep) || !existsSync(absolute) || !statSync(absolute).isFile()) {
          throw new Error(`Package contribution must be an existing file inside ${packageRoot}: ${path}`);
        }
        return relative(root, absolute).split(sep).join("/");
      };
      return {
        ...manifest,
        definitions: modulePath(manifest.definitions),
        shared: (manifest.shared ?? []).map(modulePath),
        server: (manifest.server ?? []).map(modulePath),
        schema: (manifest.schema ?? []).map(modulePath),
        migrations: (manifest.migrations ?? []).map(modulePath),
        browser: Object.fromEntries(Object.entries(manifest.browser ?? {}).map(([key, value]) => [key, modulePath(value)])),
        startup: manifest.startup ? modulePath(manifest.startup) : undefined,
        storage: manifest.storage ? modulePath(manifest.storage) : undefined,
        metadata: manifest.metadata ? modulePath(manifest.metadata) : undefined,
        client: manifest.client ? modulePath(manifest.client) : undefined,
        contributions: manifest.contributions ? modulePath(manifest.contributions) : undefined,
        coreMigrations: (manifest.coreMigrations ?? []).map(modulePath),
        maintenanceGuards: Object.fromEntries(Object.entries(manifest.maintenanceGuards ?? {}).map(([path, guard]) => [modulePath(path), guard])),
      };
    });
}

export function generateComponentPackages(root = resolve(import.meta.dirname, "..")) {
  const packages = discoverComponentPackages(root);
  const pages = new Set<string>();
  for (const pkg of packages) for (const key of Object.keys(pkg.browser)) {
    if (pages.has(key)) throw new Error(`Duplicate package browser contribution: ${key}`);
    pages.add(key);
  }
  const header = "// Generated by scripts/component-packages.ts; do not edit.\n";
  const emit = (file: string, lines: string[]) => {
    const output = header + lines.join("\n") + "\n";
    const path = resolve(root, file);
    mkdirSync(dirname(path), { recursive: true });
    if (!existsSync(path) || readFileSync(path, "utf8") !== output) writeFileSync(path, output);
  };
  const spec = (file: string, target: string) =>
    JSON.stringify("./" + relative(dirname(resolve(root, file)), resolve(root, target)).split(sep).join("/").replace(/\.tsx?$/, ""));
  const sharedFile = "shared/generated/component-packages.ts";
  emit(sharedFile, [
    'import type { ComponentDefinition } from "../components";',
    ...packages.map((p, i) => `import { components as definitions${i} } from ${spec(sharedFile, p.definitions)};`),
    `export const installedPackages = ${JSON.stringify(packages.map(p => ({ id: p.id })))};`,
    `export const packageComponents: ComponentDefinition[] = [${packages.map((_, i) => `...definitions${i}`).join(",")}];`,
    `export const componentPackageIds: Record<string, string> = Object.fromEntries([${packages.map((p, i) => `...definitions${i}.map(c => [c.id, ${JSON.stringify(p.id)}])`).join(",")}]);`,
  ]);
  const sharedModulesFile = "shared/generated/package-modules.ts";
  emit(sharedModulesFile, packages.flatMap(p => p.shared.map(path => `export * from ${spec(sharedModulesFile, path)};`)).concat("export {};"));
  const contributionsFile = "shared/generated/package-contributions.ts";
  const contributors = packages.filter(p => p.contributions);
  emit(contributionsFile, [
    'import type { PackageContributions } from "../package-contributions";',
    ...contributors.map((p, i) => `import { contributions as contribution${i} } from ${spec(contributionsFile, p.contributions!)};`),
    `export const packageContributions: PackageContributions[] = [${contributors.map((_, i) => `contribution${i}`).join(",")}];`,
  ]);
  const schemaFile = "shared/generated/package-schema.ts";
  emit(schemaFile, packages.flatMap(p => p.schema.map(path => `export * from ${spec(schemaFile, path)};`)).concat("export {};"));
  const schemasFile = "server/generated/package-schemas.ts";
  emit(schemasFile, [
    "export const packageSchemaLoaders: Record<string, () => Promise<Record<string, unknown>>> = {",
    ...packages.flatMap(p => p.schema.map(path => `${JSON.stringify("./" + path)}: () => import(${spec(schemasFile, path)}),`)),
    "};",
  ]);
  const serverFile = "server/generated/component-packages.ts";
  const modulesFile = "server/generated/package-server-modules.ts";
  emit(modulesFile, packages.flatMap(p => p.server.map(path => `import ${spec(modulesFile, path)};`)).concat("export {};"));
  const startups = packages.filter(p => p.startup);
  emit(serverFile, [
    'import type { PackageStartup } from "../services/component-package-types";',
    'import "./package-server-modules";',
    ...startups.map((p, i) => `import * as startup${i} from ${spec(serverFile, p.startup!)};`),
    `export const packageStartups: PackageStartup[] = [${startups.map((_, i) => `startup${i}`).join(",")}];`,
  ]);
  const storageFile = "server/generated/package-storage.ts";
  const stores = packages.filter(p => p.storage);
  emit(storageFile, [
    ...stores.map((p, i) => `import { createStorage as create${i} } from ${spec(storageFile, p.storage!)};`),
    `export function createPackageStorage() { return {${stores.map((_, i) => `...create${i}()`).join(",")}}; }`,
    "export type PackageStorage = ReturnType<typeof createPackageStorage>;",
  ]);
  const metadataFile = "server/generated/package-metadata.ts";
  const metadata = packages.filter(p => p.metadata);
  emit(metadataFile, [
    ...metadata.map((p, i) => `import { metadataContexts as contexts${i} } from ${spec(metadataFile, p.metadata!)};`),
    `export const packageMetadataContexts = {${metadata.map((_, i) => `...contexts${i}`).join(",")}};`,
  ]);
  const browserFile = "client/src/generated/component-packages.ts";
  emit(browserFile, [
    'import { lazy, type ComponentType, type LazyExoticComponent } from "react";',
    'import type { PackageBrowserContributions } from "../lib/package-contributions";',
    ...packages.filter(p => p.client).map((p, i) => `import { contributions as contribution${i} } from ${spec(browserFile, p.client!)};`),
    `export const packageBrowserContributions: PackageBrowserContributions[] = [${packages.filter(p => p.client).map((_, i) => `contribution${i}`).join(",")}];`,
    "export const packagePages: Record<string, LazyExoticComponent<ComponentType<any>> | undefined> = {",
    ...packages.flatMap(p => Object.entries(p.browser).map(([key, path]) => `${JSON.stringify(key)}: lazy(() => import(${spec(browserFile, path)})),`)),
    "};",
  ]);
  const migrationFile = "scripts/migrate/generated-packages.ts";
  emit(migrationFile, packages.flatMap(p => [...p.coreMigrations, ...p.migrations].map(path => `import ${spec(migrationFile, path)};`)).concat("export {};"));
  return packages;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Discovered ${generateComponentPackages().length} optional component package(s)`);
}
