import { existsSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { expect, it } from "vitest";

it("keeps maintained host files independent of the Freeman components", () => {
  const files = execFileSync("git", ["ls-files", "-co", "--exclude-standard", "-z"], { encoding: "utf8" }).split("\0");
  const violations = new Set<string>();
  for (const file of files) {
    // This protects core. Component integrations are checked by dependency lint.
    if (!file || file.startsWith("components/") || /^\.(agents|local)\//.test(file) || !existsSync(file)) continue;
    if (!/\.(ts|tsx|js|mjs|json|md|sql|sh|ya?ml|toml)$/.test(file) && ![".replit", ".gitignore", ".replitignore"].includes(file)) continue;
    const source = readFileSync(file, "utf8");
    if (source.startsWith("// Generated by scripts/optional-components.ts;")) continue;
    if (/freeman/i.test(file) || /freeman/i.test(source)) violations.add(file);
  }
  expect([...violations].sort()).toEqual([]);
});
